import streamlit as st
import pandas as pd
import numpy as np
import pickle
import joblib

# Load model and feature column names
model = joblib.load('rfr_cars_price_pred_compressed.pkl')
columns = pickle.load(open('columns.pkl', 'rb'))

st.title("Car Price Predictor")

# User Inputs
year = st.number_input("Year", min_value=1990, max_value=2025, step=1)
engine_size = st.number_input("Engine Size", min_value=0.5, max_value=10.0, step=0.1)
mileage = st.number_input("Mileage (in km)", min_value=0, max_value=500000, step=100)
owner_count = st.selectbox("Owner Count", options=[1, 2, 3, 4])

model_input = st.selectbox("Model", options=[col.replace('Model_', '') for col in columns if col.startswith('Model_')])
fuel_type = st.selectbox("Fuel Type", options=['Diesel', 'Petrol', 'Electric', 'Hybrid'])
transmission = st.selectbox("Transmission", options=['Automatic', 'Manual', 'Semi-Automatic'])

# Construct input vector
input_dict = {
    'Year': year,
    'Engine_Size': engine_size,
    'Mileage': mileage,
    'Owner_Count': owner_count
}

# Add encoded columns
for col in columns:
    if col not in input_dict:
        input_dict[col] = 0

input_dict[f'Model_{model_input}'] = 1
input_dict[f'Fuel_Type_{fuel_type}'] = 1
input_dict[f'Transmission_{transmission}'] = 1

# Convert to DataFrame
input_df = pd.DataFrame([input_dict])
input_df = input_df[columns]  # Ensure correct column order

if st.button("Predict"):
    prediction = model.predict(input_df)[0]
    st.success(f"Estimated Car Price: {round(prediction, 2)}")